const normalise = (value: string) =>
  value
    .toLowerCase()
    .replace(
      /\b(b\.sc\.|bachelor|of|science|engineering|doctor|medicine|agriculture|and|the)\b/g,
      " ",
    )
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

const aliases: Record<string, string[]> = {
  "agricultural engineering": [
    "agricultural and bio resources engineering",
    "agricultural bio resources engineering",
  ],
  "mechatronic engineering": ["mechatronics engineering"],
  "hospitality and tourism": ["hospitality and tourism management"],
  "veterinary medicine": ["veterinary medicine"],
  "clothing textile design": ["clothing and textile", "clothing and textile design"],
  "library and information science": ["library and information studies"],
};

export function courseBankFor(programme: string, level?: string) {
  const key = normalise(programme);
  const candidates = [key, ...(aliases[key] || []).map(normalise)];
  const rows = funaabCourseBank.filter((row) => {
    const rowKey = normalise(row.programme);
    return candidates.some(
      (candidate) =>
        rowKey === candidate || rowKey.includes(candidate) || candidate.includes(rowKey),
    );
  });
  if (!level) return rows;
  return rows.filter((row) => row.level.toLowerCase() === level.toLowerCase());
}

export function courseBankLevelsFor(programme: string) {
  return [...new Set(courseBankFor(programme).map((row) => row.level))].sort(
    (a, b) => Number.parseInt(a) - Number.parseInt(b),
  );
}
